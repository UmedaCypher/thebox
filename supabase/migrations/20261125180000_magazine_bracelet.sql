$md$Changing the strap is the simplest, cheapest way to transform a watch. The same piece goes from dressy to sporty, summer to winter, in two minutes. You just need the right width, the right length and the right material, and to remove the old one without scratching the case. Here's everything you need to know.

## 1. Measure the lug width

**Lug width** is the distance between the two lugs of the watch, where the strap attaches. It's the one measurement you can't skip: a strap that's too narrow leaves an ugly gap and shifts around, one that's too wide won't fit.

- **Where to find it**: often stamped on the back of the original strap ("20", "20-18"), or listed in the manufacturer's specs.
- **How to measure it**: place a ruler, or better a caliper, between the lugs, on the inside. The result is almost always a whole number of millimetres.
- **Common widths**: 18, 20 and 22 mm for most watches, but also 19, 21 or 24 mm.

Don't confuse lug width with **lug-to-lug**, the distance from the tip of one lug to the other, which is mostly used to judge whether a watch suits your wrist. Our guide to [watch size](/en/magazine/watch-size-for-wrist/) explains it in detail.

Save the lug width on your watch's page in Arcora ("Lug width" field): you'll have it to hand when you shop for a strap.

## 2. Choose the length

A two-piece strap is measured by the length of each piece: the buckle side (short) and the holes side (long). The most common sizes:

| Size | Long side / short side | Approximate wrist size |
|---|---|---|
| Short | about 110 / 70 mm | under 6.3 in (16 cm) |
| Regular | about 120 / 75 mm | 6.3–7.5 in (16–19 cm) |
| Long | about 130 / 80 mm | over 7.5 in (19 cm) |

These vary between brands and with strap thickness. The right fit: the buckle sits on a hole in the middle of the row, and you can slide one finger between the strap and your wrist.

## 3. Taper and thickness

Many leather straps narrow toward the buckle: a "20-18" strap is 20 mm at the lugs and 18 mm at the buckle. A strong taper looks slimmer and dressier; a straight strap looks sportier. Thickness matters too: thick leather suits a dive watch, thin leather a dress watch.

## 4. Remove and fit a strap without scratching the watch

The strap is held by two **spring bars**: small rods whose ends retract under pressure and pop into the holes in the lugs.

1. **Protect the lugs** with a little masking tape: it's the best insurance against scratches.
2. **Turn the watch over** onto a soft cloth, dial down.
3. **Slide the forked end of a spring bar tool** between the strap and the lug, onto the shoulder of the spring bar, and push it toward the centre of the strap. That side of the strap comes free.
4. **To refit**, put the spring bar through the strap, seat one end in its hole, compress the other end with the tool and let it snap into the opposite hole.
5. **Tug firmly on the strap**: a clean click, no play. A badly seated spring bar is the number one reason watches end up on the floor.

Many recent straps have **quick-release spring bars** with a small lever: they swap in seconds, no tool needed. And if a spring bar is bent or weak, replace it: a few euros against a dropped watch is an easy call.

## 5. Which material for which use?

**Leather.** The classic: warm, comfortable, and it develops a patina over time. Keep it out of water and intense heat, as sweat and moisture damage it. Be wary of vague labels like "genuine leather", which often means lower-grade leather; full-grain leather ages far better.

**NATO and fabric.** A single band of fabric that passes under the watch. Tough, washable, inexpensive, with a safety bonus: if one spring bar fails, the other still holds the watch. The trade-off is that the watch sits a little higher on the wrist.

**Rubber.** The choice for water and sport. Go for FKM or vulcanised rubber, which are softer and last longer than cheap silicone.

**Steel.** A metal bracelet attaches with end links shaped to fit the case: a generic one often leaves unsightly gaps. Milanese mesh is the exception, with straight end pieces that suit many watches.

## 6. Watches that are different

Some watches don't take standard straps: bracelets integrated into the case (Tissot PRX, Royal Oak, Nautilus…), proprietary attachments, or unusually shaped lugs. For those you need a strap made for the model, or an adapter.

