$md$You take your watch off in the evening, and by morning it shows the wrong time. Or it stops in the middle of the day, on your wrist. In most cases the watch isn't broken: it has simply run out of energy. Here are the eight possible causes, from most to least common, and how to tell which one applies to you.

## How an automatic watch winds itself

An automatic watch draws its energy from a spring, the mainspring, inside the barrel. A weighted rotor spins with every movement of your wrist and winds that spring. The spring then slowly releases its energy to drive the movement.

Two numbers matter:

- **power reserve**: how long the watch runs, fully wound, without being worn. For many common calibres it's around 38 to 42 hours (ETA 2824, Sellita SW200, Seiko NH35). Some recent movements go much further, like the Powermatic 80 with its 80 hours;
- **how wound it actually is**: a half-wound spring only gives part of that reserve.

## 1. The power reserve has run out

This is cause number one. A watch put down on Friday evening with 40 hours of reserve stops around Sunday lunchtime. That's normal, and it's exactly what happens to the watches in a collection that aren't worn every day.

**What to do:** wind it and set the time before wearing it. If you rotate several watches, this is unavoidable, unless you use a watch winder (see below).

## 2. It wasn't wound enough on the wrist

The rotor needs movement. A day sitting at a screen, a watch worn for only a couple of hours, or a fairly still wrist won't always wind the spring fully. The watch runs on the wrist, then stops overnight.

**What to do:** give it a "full tank" with the crown before putting it on, if your calibre allows it (see cause 3). From a stopped watch, roughly thirty to forty turns is usually enough. There's no risk of overwinding an automatic: a slipping clutch lets the spring slide once it's fully wound.

## 3. Your calibre can't be wound by hand

Some movements have no manual winding. That's the case, for example, with the older Seiko 7S26 found in many Seiko 5 models made before 2019. Shaking the watch restarts it but gives it very little energy.

**What to do:** wear it longer, or use a winder when it's resting. If you don't know whether your calibre hand-winds, gently turn the crown in its first position: if the seconds hand starts after a few turns, it does.

## 4. The crown was left pulled out

On many watches, pulling the crown out to set the time deliberately stops the seconds hand ("hacking"). A crown not pushed all the way in, or a screw-down crown not screwed back, gives you a watch that looks stopped.

**What to do:** push the crown fully in and screw it down if it's a screw-down crown. That also matters for water resistance.

## 5. The watch is magnetised

Speakers, bag clasps, phone cases, induction hobs: a magnetic field can make the coils of the hairspring, the tiny spring that regulates the balance, stick together. Most often the watch starts gaining several minutes a day; in some cases, it stops.

**What to do:** a watchmaker can demagnetise it in seconds, often for free or for a small fee. Measure the watch before and after with a [timegrapher](/en/magazine/how-to-read-timegrapher/): if the rate goes back to normal, you've found the cause.

## 6. The movement needs a service

Over the years, oils dry out and friction increases. The balance swings less strongly, the real power reserve shrinks, and the watch stops earlier and earlier. This is especially likely if the last service was more than five to ten years ago.

**What to do:** a timegrapher that measures amplitude gives a good indication, but the diagnosis is the watchmaker's job. Our article on [servicing an automatic watch](/en/magazine/automatic-watch-service-interval/) explains what a service involves and how often to plan one.

## 7. The automatic winding has stopped working

If the watch runs normally after being wound by hand but still stops even though you wear it every day, the rotor or its reverser mechanism may be at fault: a stuck rotor, worn wheels, a loose screw. An unusual noise or a rotor that rubs are clues.

**What to do:** don't force anything and take it to a watchmaker. This kind of fault gets worse if you wait.

## 8. A knock or a broken part

A drop, even onto a wooden floor, can break a pivot or shift a part. The watch stops dead, or restarts for a few seconds when shaken and then stops again.

**What to do:** straight to a watchmaker, without repeatedly trying to restart it.

## A 3-step test to find the cause

1. **Wind the watch by hand** (30 to 40 turns), set the time and put it down without wearing it. Note the time.
2. **See when it stops.** If it runs for roughly its stated power reserve, the movement is fine: the problem was a lack of winding (causes 1 to 3).
3. **If it stops much earlier**, or won't restart, think magnetism, a service or a fault (causes 5 to 8).

## Do you need a watch winder?

A winder turns the watch to keep it wound. It's handy for a perpetual calendar or moonphase watch that takes a long time to set, or for a watch you want to find running at any moment. For a simple watch it isn't necessary: letting it stop doesn't harm it. If you use one, set the turns per day to the brand's recommendation, often between 650 and 950.

