## En résumé

- Mesurez l'**entrecorne** à l'intérieur des cornes, et notez-la dans la fiche de votre montre.
- Choisissez la **longueur** selon votre tour de poignet : la boucle doit tomber au milieu des trous.
- Protégez les cornes au ruban adhésif avant de démonter, et vérifiez chaque pompe d'un coup sec.
- Cuir pour le quotidien au sec, NATO pour la robustesse, caoutchouc pour l'eau, acier avec des embouts adaptés.

