## In short

- An automatic stops first because of **a lack of energy**: an empty reserve or not enough winding.
- Give it around thirty turns of the crown before wearing it, if the calibre allows.
- A watch that stops long before its stated reserve, suddenly runs fast or makes an unusual noise should be seen by a watchmaker.

## Frequently asked questions

### Why does my automatic watch stop overnight?

Most often because it wasn't wound enough during the day. The rotor didn't fully wind the spring, and the reserve runs out overnight. Give it about thirty turns of the crown in the morning: if it then runs through the night, the movement is fine.

### Can you overwind an automatic watch?

No. An automatic has a slipping clutch that lets the mainspring slide once it's fully wound, so you can hand-wind it safely. A manual-wind watch, on the other hand, has a stop: quit as soon as you feel resistance.

### Is it bad to let an automatic watch stop?

No, letting it stop doesn't harm it. You'll just need to wind it and set the time again, which can take a while on a calendar or moonphase watch. In that case, a watch winder can be useful.
