$md$Changer de bracelet est la façon la plus simple, et la moins chère, de transformer une montre. La même pièce passe d'habillée à sportive, d'été à hiver, en deux minutes. Encore faut-il choisir la bonne largeur, la bonne longueur et la bonne matière, et démonter l'ancien sans rayer le boîtier. Voici tout ce qu'il faut savoir.

## 1. Mesurer l'entrecorne

L'**entrecorne** est la largeur entre les deux cornes de la montre, là où s'attache le bracelet. C'est la seule mesure vraiment obligatoire : un bracelet trop étroit laisse un vide disgracieux et bouge, un bracelet trop large ne rentre pas.

- **Où la trouver** : souvent gravée au dos du bracelet d'origine (« 20 », « 20-18 »), ou indiquée sur la fiche technique du fabricant.
- **Comment la mesurer** : posez une règle graduée, ou mieux un pied à coulisse, entre les cornes, à l'intérieur. La mesure tombe presque toujours sur un nombre entier de millimètres.
- **Les largeurs courantes** : 18, 20 et 22 mm pour la plupart des montres, mais aussi 19, 21 ou 24 mm.

Ne confondez pas l'entrecorne avec la **longueur corne à corne** (*lug-to-lug*), la distance d'une extrémité de corne à l'autre, qui sert surtout à juger si une montre convient à votre poignet. Notre guide sur [la taille de montre](/magazine/taille-montre-poignet/) l'explique en détail.

Notez l'entrecorne dans la fiche de votre montre sur Arcora (champ « Entrecorne ») : vous l'aurez sous la main le jour où vous chercherez un bracelet.

## 2. Choisir la longueur

Un bracelet en deux parties se mesure par la longueur de chaque partie : le côté boucle (court) et le côté trous (long). Les tailles les plus fréquentes :

| Taille | Côté long / côté court | Tour de poignet indicatif |
|---|---|---|
| Courte | environ 110 / 70 mm | moins de 16 cm |
| Standard | environ 120 / 75 mm | 16 à 19 cm |
| Longue | environ 130 / 80 mm | plus de 19 cm |

Ces repères varient d'une marque à l'autre et selon l'épaisseur du bracelet. Le bon réglage : la boucle tombe sur un trou au milieu de la série, et vous glissez un doigt entre le bracelet et le poignet.

## 3. La dégressivité et l'épaisseur

Beaucoup de bracelets en cuir se rétrécissent vers la boucle : un bracelet « 20-18 » mesure 20 mm aux cornes et 18 mm à la boucle. Une forte dégressivité donne une allure plus fine et habillée ; un bracelet droit, plus sportive. L'épaisseur compte aussi : un cuir épais va bien à une montre de plongée, un cuir fin à une montre habillée.

## 4. Démonter et remonter sans rayer la montre

Le bracelet tient grâce à deux **pompes** (ou barrettes à ressort) : de petites tiges dont les extrémités rentrent sous la pression et ressortent dans les trous des cornes.

1. **Protégez les cornes** avec un peu de ruban adhésif de masquage : c'est la meilleure assurance contre les rayures.
2. **Retournez la montre** sur un chiffon doux, cadran vers le bas.
3. **Glissez la fourche d'un outil à pompes** entre le bracelet et la corne, sur l'épaulement de la pompe, et poussez-la vers le centre du bracelet. Le bracelet se libère d'un côté.
4. **Pour remonter**, placez la pompe dans le bracelet, engagez une extrémité dans son trou, comprimez l'autre avec l'outil et laissez-la se loger dans le trou opposé.
5. **Tirez fermement sur le bracelet** : un clic net, aucun jeu. Une pompe mal engagée est la cause n°1 des montres qui tombent.

Beaucoup de bracelets récents ont des **pompes à libération rapide**, avec un petit levier : on les change en quelques secondes, sans outil. Et si une pompe est tordue ou molle, remplacez-la : quelques euros contre une montre au sol, le calcul est vite fait.

## 5. Quelle matière pour quel usage ?

**Le cuir.** Le grand classique, chaleureux et confortable, qui se patine avec le temps. Évitez-le dans l'eau et par forte chaleur : la transpiration et l'humidité l'abîment. Méfiez-vous des mentions vagues comme « cuir véritable », qui désignent souvent un cuir de qualité modeste ; un cuir pleine fleur vieillit bien mieux.

**Le NATO et la toile.** Une seule bande de tissu qui passe sous la montre. Robuste, lavable, bon marché, avec un avantage de sécurité : si une pompe lâche, la montre reste retenue par l'autre. En contrepartie, la montre est un peu surélevée au poignet.

**Le caoutchouc.** Le choix de l'eau et du sport. Préférez le FKM ou le caoutchouc vulcanisé, plus souples et plus durables que le silicone bas de gamme.

**L'acier.** Un bracelet métal se fixe avec des embouts (*end links*) taillés pour la forme du boîtier : un modèle générique laisse souvent des jours disgracieux. Le maillage milanais est l'exception, avec ses embouts droits qui s'adaptent à beaucoup de montres.

## 6. Les montres à part

Certaines montres n'acceptent pas les bracelets standards : bracelets intégrés au boîtier (Tissot PRX, Royal Oak, Nautilus…), attaches propriétaires, ou cornes percées d'une forme particulière. Pour celles-là, il faut un bracelet conçu pour le modèle, ou un adaptateur.

