$md$Vous retirez votre montre le soir, et le matin elle affiche une heure fantaisiste. Ou elle s'arrête en pleine journée, au poignet. Dans la grande majorité des cas, la montre n'est pas cassée : elle manque simplement d'énergie. Voici les huit causes possibles, de la plus fréquente à la plus rare, et comment savoir laquelle vous concerne.

## Comment se remonte une montre automatique

Une montre automatique tire son énergie d'un ressort, le barillet. Une masse oscillante, le rotor, tourne à chaque mouvement du poignet et tend ce ressort. Le ressort se détend ensuite lentement pour faire tourner le mouvement.

Deux chiffres comptent :

- **la réserve de marche** : combien de temps la montre fonctionne, ressort bien tendu, sans être portée. Pour beaucoup de calibres courants, c'est autour de 38 à 42 heures (ETA 2824, Sellita SW200, Seiko NH35). Certains mouvements récents vont bien au-delà, comme le Powermatic 80 et ses 80 heures ;
- **le niveau de remontage réel** : un ressort à moitié tendu ne donne qu'une partie de cette réserve.

## 1. La réserve de marche est épuisée

C'est la cause n°1. Une montre posée vendredi soir avec 40 heures de réserve s'arrête dimanche midi. C'est normal, et c'est exactement ce qui arrive aux montres d'une collection qui ne sont pas portées tous les jours.

**Que faire :** remontez-la et remettez-la à l'heure avant de la porter. Si vous alternez plusieurs montres, c'est inévitable, sauf à utiliser un remontoir (voir plus bas).

## 2. Elle n'a pas été assez remontée au poignet

Le rotor a besoin de mouvement. Une journée assise devant un écran, une montre portée deux heures seulement, ou un poignet peu actif ne suffisent pas toujours à tendre complètement le ressort. La montre fonctionne au poignet, puis s'arrête dans la nuit.

**Que faire :** donnez-lui un « plein » à la couronne avant de la mettre, si votre calibre le permet (voir la cause n°3). En général, une trentaine à une quarantaine de tours suffisent à partir d'une montre arrêtée. Il n'y a aucun risque de trop remonter une automatique : un système de friction laisse glisser le ressort une fois tendu.

## 3. Votre calibre ne se remonte pas à la couronne

Certains mouvements n'ont pas de remontage manuel. C'est le cas, par exemple, de l'ancien calibre Seiko 7S26 que l'on trouve dans beaucoup de montres Seiko 5 d'avant 2019. Secouer la montre la relance, mais ne lui donne que très peu d'énergie.

**Que faire :** portez-la plus longtemps, ou utilisez un remontoir quand elle reste au repos. Si vous ne savez pas si votre calibre se remonte à la couronne, tournez-la doucement en position 1 : si la trotteuse repart après quelques tours, c'est le cas.

## 4. La couronne est restée tirée

Sur beaucoup de montres, tirer la couronne en position de mise à l'heure arrête volontairement la trotteuse (le « stop seconde »). Une couronne mal repoussée, ou une couronne vissée mal revissée, donne une montre qui semble arrêtée.

**Que faire :** repoussez la couronne à fond et revissez-la si elle est vissée. C'est aussi essentiel pour l'étanchéité.

## 5. La montre est aimantée

Haut-parleurs, fermoirs de sacs, coques de téléphone, plaques à induction : un champ magnétique peut coller entre elles les spires du spiral, le petit ressort qui règle le balancier. Le plus souvent, la montre se met à avancer de plusieurs minutes par jour ; dans certains cas, elle s'arrête.

**Que faire :** un horloger la démagnétise en quelques secondes, souvent gratuitement ou pour un prix modique. Mesurez la montre avant et après avec un [timegrapher](/magazine/timegrapher-lire-mesure-montre/) : si la marche revient à la normale, la cause est trouvée.

## 6. Le mouvement a besoin d'une révision

Avec les années, les huiles sèchent et les frottements augmentent. Le balancier oscille moins fort, la réserve de marche réelle diminue, et la montre s'arrête de plus en plus tôt. C'est particulièrement probable si la dernière révision remonte à plus de cinq à dix ans.

**Que faire :** un timegrapher qui mesure l'amplitude donne une bonne indication, mais le diagnostic revient à l'horloger. Notre article sur [la révision d'une montre automatique](/magazine/reviser-montre-automatique/) explique ce qu'elle comprend et à quelle fréquence la prévoir.

## 7. Le remontage automatique ne fonctionne plus

Si la montre fonctionne normalement après un remontage à la couronne, mais s'arrête quand même alors que vous la portez tous les jours, le rotor ou son mécanisme d'inversion peut être en cause : rotor bloqué, roues usées, vis desserrée. Un bruit inhabituel ou un rotor qui « frotte » sont des indices.

**Que faire :** ne forcez rien et confiez la montre à un horloger. Ce genre de panne s'aggrave si on attend.

## 8. Un choc ou une pièce cassée

Une chute, même sur un parquet, peut casser un pivot ou déplacer une pièce. La montre s'arrête net, ou repart quelques secondes quand on la secoue puis s'arrête à nouveau.

**Que faire :** direction l'horloger, sans essayer de la relancer en boucle.

## Le test en 3 étapes pour trouver la cause

1. **Remontez la montre à la couronne** (30 à 40 tours), mettez-la à l'heure et posez-la sans la porter. Notez l'heure.
2. **Regardez quand elle s'arrête.** Si elle tient environ sa réserve de marche annoncée, le mouvement va bien : le problème venait d'un manque de remontage (causes 1 à 3).
3. **Si elle s'arrête beaucoup plus tôt**, ou ne repart pas, pensez au magnétisme, à une révision ou à une panne (causes 5 à 8).

## Faut-il un remontoir ?

Un remontoir fait tourner la montre pour la garder remontée. C'est pratique pour une montre à quantième perpétuel ou à phases de lune, longue à régler, ou pour une montre que vous voulez trouver à l'heure à tout moment. Pour une montre simple, ce n'est pas nécessaire : la laisser s'arrêter ne l'abîme pas. Si vous en utilisez un, réglez le nombre de tours par jour selon la recommandation de la marque, souvent entre 650 et 950.

