## Questions fréquentes

### Pourquoi ma montre automatique s'arrête-t-elle la nuit ?

Le plus souvent parce qu'elle n'a pas été assez remontée dans la journée. Le rotor n'a pas tendu complètement le ressort, et la réserve s'épuise pendant la nuit. Donnez-lui une trentaine de tours de couronne le matin : si elle tient ensuite toute la nuit, le mouvement va bien.

### Peut-on trop remonter une montre automatique ?

Non. Une automatique possède un système de friction qui laisse glisser le ressort une fois qu'il est tendu. Vous pouvez remonter à la couronne sans risque. Une montre à remontage manuel, elle, a une butée : arrêtez-vous dès que vous sentez une résistance.

