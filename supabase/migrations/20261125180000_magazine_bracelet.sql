## Frequently asked questions

### How do I find my watch's strap size?

Measure the lug width, the distance between the lugs on the inside, with a ruler or caliper. It's often stamped on the back of the original strap. The most common widths are 18, 20 and 22 mm.

### Can I fit a 20 mm strap on a 21 mm lug width?

You can, but a millimetre of play shows and the strap slides along the spring bars. The exact width is better. A strap that's too wide, on the other hand, won't fit without being trimmed.

### Do I need a tool to change a watch strap?

For standard spring bars, a spring bar tool with a forked end makes the job easy and safe; a small screwdriver will do in a pinch, with tape on the lugs. Straps with quick-release spring bars can be changed without any tool.
